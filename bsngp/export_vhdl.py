#!/usr/bin/env python3
"""
Generate VHDL from the exported integer model (bsngp/export/params.npz):
  rtl/bsngp_params_pkg.vhd     weights, thresholds, RFF tables, cos ROM, GP head
  rtl/bsngp_demo_rom_pkg.vhd   on-chip demo sample ROM (stand-alone board demo)
  sim/stream.txt, sim/expected_stream.txt          core co-simulation vectors
  sim/demo_expected.txt                            ROM-mode expected results
This script only formats numbers; it runs no model.
"""

import os
import argparse
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
EXPORT = os.path.join(HERE, "export")
RTL = os.path.join(HERE, "rtl")
SIM = os.path.join(HERE, "sim")


def slv(bits):
    """bits[0] is the LSB. Returns a VHDL string literal MSB first."""
    return '"' + "".join("1" if b else "0" for b in reversed(list(bits))) + '"'


def int_list(vals, per_line=16, indent="        "):
    vals = [str(int(v)) for v in vals]
    lines = [", ".join(vals[i:i + per_line]) for i in range(0, len(vals), per_line)]
    return (",\n" + indent).join(lines)


def gen_params_pkg(p, src="export"):
    c1, c2, c3 = len(p["th1"]), len(p["th2"]), len(p["th3"])
    d, r = p["beta"].shape[0], p["u"].shape[0]
    beta0 = int(p["beta0"])
    assert abs(beta0) < 2 ** 31 - 1
    assert int(p["tv"]) < 2 ** 31 - 1 and abs(int(p["tl"])) < 2 ** 31 - 1

    def wconv(w, cin):
        # bit index k*cin + i  <-  w[c, i, k]
        rows = []
        for c in range(w.shape[0]):
            bits = [0] * (3 * cin)
            for k in range(3):
                for i in range(cin):
                    bits[k * cin + i] = int(w[c, i, k])
            rows.append(f"        {c} => {slv(bits)}")
        return ",\n".join(rows)

    def dirv(dv):
        return slv([1 if x > 0 else 0 for x in dv])

    L = []
    L.append(f"-- AUTO-GENERATED by bsngp/export_vhdl.py from bsngp/{src}/params.npz. Do not edit.")
    L.append("library ieee;\nuse ieee.std_logic_1164.all;\n")
    L.append("package bsngp_params_pkg is")
    L.append(f"    constant C1    : natural := {c1};")
    L.append(f"    constant C2    : natural := {c2};")
    L.append(f"    constant C3    : natural := {c3};")
    L.append(f"    constant D     : natural := {d};")
    L.append(f"    constant R     : natural := {r};")
    L.append(f"    constant KSH   : natural := {int(p['ksh'])};")
    L.append(f"    constant QSH   : natural := {int(p['qsh'])};")
    L.append(f"    constant TL    : integer := {int(p['tl'])};")
    L.append(f"    constant TV    : integer := {int(p['tv'])};")
    L.append(f"    constant BETA0 : integer := {beta0};")
    L.append(f"    constant DC_REMOVE : boolean := {'true' if int(p.get('dc_remove', 0)) else 'false'};  -- per-window mean removal")
    L.append("")
    L.append("    type int_array_t is array (natural range <>) of integer;")
    L.append(f"    type w1_t is array (0 to C1-1) of std_logic_vector(3*6-1 downto 0);   -- bit k*6+i")
    L.append(f"    type w2_t is array (0 to C2-1) of std_logic_vector(3*C1-1 downto 0);  -- bit k*C1+i")
    L.append(f"    type w3_t is array (0 to C3-1) of std_logic_vector(3*C2-1 downto 0);  -- bit k*C2+i")
    L.append(f"    type wr_t is array (0 to D-1) of std_logic_vector(C3-1 downto 0);")
    L.append(f"    type cos_t is array (0 to 1023) of integer range -127 to 127;")
    L.append(f"    type s8_d_t is array (0 to D-1) of integer range -127 to 127;")
    L.append(f"    type ucol_t is array (0 to D-1) of std_logic_vector(8*R-1 downto 0);  -- U(k, j) at bits 8k+7..8k of word j")
    L.append("")
    L.append(f"    constant W1 : w1_t := (\n{wconv(p['w1'], 6)}\n    );")
    L.append(f"    constant TH1 : int_array_t(0 to C1-1) := (\n        {int_list(p['th1'])}\n    );")
    L.append(f"    constant DIR1 : std_logic_vector(C1-1 downto 0) := {dirv(p['dir1'])};  -- '1': acc >= TH")
    L.append(f"    constant W2 : w2_t := (\n{wconv(p['w2'], c1)}\n    );")
    L.append(f"    constant TH2 : int_array_t(0 to C2-1) := (\n        {int_list(p['th2'])}\n    );")
    L.append(f"    constant DIR2 : std_logic_vector(C2-1 downto 0) := {dirv(p['dir2'])};")
    L.append(f"    constant W3 : w3_t := (\n{wconv(p['w3'], c2)}\n    );")
    L.append(f"    constant TH3 : int_array_t(0 to C3-1) := (\n        {int_list(p['th3'])}\n    );")
    L.append(f"    constant DIR3 : std_logic_vector(C3-1 downto 0) := {dirv(p['dir3'])};")
    wr_rows = ",\n".join(f"        {j} => {slv(p['wr'][j])}" for j in range(d))
    L.append(f"    constant WR : wr_t := (\n{wr_rows}\n    );")
    L.append(f"    constant BR : int_array_t(0 to D-1) := (\n        {int_list(p['br'])}\n    );")
    L.append(f"    constant COS_LUT : cos_t := (\n        {int_list(p['cos_lut'])}\n    );")
    L.append(f"    constant BETA : s8_d_t := (\n        {int_list(p['beta'])}\n    );")
    ucol = []
    for j in range(d):
        word = 0
        for k in range(r):
            word |= (int(p["u"][k, j]) & 0xFF) << (8 * k)
        ucol.append(f'        {j} => x"{word:0{2 * r}X}"')
    L.append("    constant UCOL : ucol_t := (\n" + ",\n".join(ucol) + "\n    );")
    L.append("end package bsngp_params_pkg;")
    return "\n".join(L) + "\n"


def pack48(row):
    v = 0
    for i, x in enumerate(row):
        v |= (int(x) & 0xFF) << (8 * i)
    return f'x"{v:012X}"'


def gen_demo_pkg(stream):
    n = len(stream)
    rows = ",\n".join(f"        {pack48(stream[i])}" for i in range(n))
    return (
        "-- AUTO-GENERATED by bsngp/export_vhdl.py. Do not edit.\n"
        "-- Demo samples (int8 x 6 per word, channel i at bits 8i+7..8i), replayed in a loop.\n"
        "library ieee;\nuse ieee.std_logic_1164.all;\n\n"
        "package bsngp_demo_rom_pkg is\n"
        f"    constant DEMO_LEN : natural := {n};\n"
        "    type demo_rom_t is array (0 to DEMO_LEN-1) of std_logic_vector(47 downto 0);\n"
        f"    constant DEMO_ROM : demo_rom_t := (\n{rows}\n    );\n"
        "end package bsngp_demo_rom_pkg;\n"
    )


def write_expected(path, exp):
    with open(path, "w") as f:
        for L, V, a, u in zip(exp["logit"], exp["var"], exp["abnormal"], exp["unknown"]):
            f.write(f"{int(L)} {int(V)} {int(a)} {int(u)}\n")


def main():
    global EXPORT
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default="export", help="export directory under bsngp/ (export or export_robust)")
    EXPORT = os.path.join(HERE, ap.parse_args().src)
    os.makedirs(SIM, exist_ok=True)
    p = dict(np.load(os.path.join(EXPORT, "params.npz")))
    open(os.path.join(RTL, "bsngp_params_pkg.vhd"), "w").write(gen_params_pkg(p, os.path.basename(EXPORT)))

    demo = np.load(os.path.join(EXPORT, "demo_stream.npy"))
    open(os.path.join(RTL, "bsngp_demo_rom_pkg.vhd"), "w").write(gen_demo_pkg(demo))

    stream = np.load(os.path.join(EXPORT, "stream.npy"))
    np.savetxt(os.path.join(SIM, "stream.txt"), stream, fmt="%d")
    write_expected(os.path.join(SIM, "expected_stream.txt"), dict(np.load(os.path.join(EXPORT, "expected_stream.npz"))))
    write_expected(os.path.join(SIM, "demo_expected.txt"), dict(np.load(os.path.join(EXPORT, "demo_expected.npz"))))
    print(f"source {EXPORT}; dc_remove={int(p.get('dc_remove', 0))}; params: C={len(p['th1'])}/{len(p['th2'])}/{len(p['th3'])} D={len(p['beta'])} R={len(p['u'])} "
          f"TL={int(p['tl'])} TV={int(p['tv'])}; stream {stream.shape}; demo {demo.shape}")


if __name__ == "__main__":
    main()
